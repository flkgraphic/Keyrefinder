/* ============================================================
   applyTranslations  –  reads data-i18n / data-i18n-ph attrs
   and sets innerHTML / placeholder accordingly.
   ============================================================ */
window.applyTranslations = function(lang) {
  const t = window.TRANSLATIONS[lang] || window.TRANSLATIONS['DE'];

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) el.innerHTML = t[key];
  });

  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const key = el.getAttribute('data-i18n-ph');
    if (t[key] !== undefined) el.placeholder = t[key];
  });

  document.querySelectorAll('[data-i18n-href]').forEach(el => {
    const key = el.getAttribute('data-i18n-href');
    if (t[key] !== undefined) el.href = t[key];
  });

  document.documentElement.lang = { DE: 'de', IT: 'it', FR: 'fr', EN: 'en' }[lang] || 'de';
};
